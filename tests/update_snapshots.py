#!/usr/bin/env python3
"""Update expected snapshots by running tests with UPDATE_EXPECTED=1.

Usage:
    python tests/update_snapshots.py                    # Update all cases
    python tests/update_snapshots.py --comp             # Update compilation tests only
    python tests/update_snapshots.py --exec             # Update execution tests only
    python tests/update_snapshots.py --cpy              # Run CPython compatibility checks (read-only)
    python tests/update_snapshots.py -k hello           # Update specific case (all types)
    python tests/update_snapshots.py --comp -k hello    # Update compilation tests for specific case

Any other arguments (e.g. -n auto) are passed directly to pytest.
"""
import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

parser = argparse.ArgumentParser(description="Update test snapshots")
parser.add_argument("--comp", action="store_true", help="Update compilation tests only")
parser.add_argument("--exec", action="store_true", help="Update execution tests only")
parser.add_argument("--cpy", action="store_true", help="Run CPython compatibility checks (read-only)")
parser.add_argument("-k", "--pattern", help="Case name pattern (passed to pytest -k)")

args, extra_pytest_args = parser.parse_known_args()

# Determine which test files to run
test_files = []
if args.comp:
    test_files.append("tests/test_comp.py")
if args.exec:
    test_files.append("tests/test_exec.py")
if args.cpy:
    test_files.append("tests/test_cpy.py")
if not test_files:
    test_files = ["tests/test_comp.py", "tests/test_exec.py", "tests/test_cpy.py"]

run_comp = "tests/test_comp.py" in test_files
run_exec = "tests/test_exec.py" in test_files

# Clear expected files before regeneration to remove stale artifacts.
# Only delete file types that will be regenerated by the selected tests:
#   test_comp: diag.txt, include/, src/
#   test_exec: output.txt, panic.txt
if run_comp or run_exec:
    cases_dir = Path(__file__).parent / "cases"
    for expected_dir in cases_dir.rglob("expected"):
        if not expected_dir.is_dir():
            continue
        case_dir = expected_dir.parent
        if args.pattern and args.pattern not in case_dir.name:
            continue
        if run_comp and run_exec:
            shutil.rmtree(expected_dir)
        elif run_comp:
            diag = expected_dir / "diag.txt"
            if diag.exists():
                diag.unlink()
            for subdir in ["include", "src"]:
                d = expected_dir / subdir
                if d.is_dir():
                    shutil.rmtree(d)
        elif run_exec:
            for fname in ["output.txt", "panic.txt"]:
                f = expected_dir / fname
                if f.exists():
                    f.unlink()

# Build pytest arguments
pytest_args = ["pytest"] + test_files + ["-v"]
if args.pattern:
    pytest_args.extend(["-k", args.pattern])
pytest_args.extend(extra_pytest_args)

result = subprocess.run(
    pytest_args,
    env={**os.environ, "UPDATE_EXPECTED": "1"}
)
sys.exit(result.returncode)
