"""Regression tests for test failure reporting helpers."""

from pathlib import Path

import pytest

import conftest


def test_check_or_update_reports_unified_diff(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """Mismatch should surface a unified diff instead of raw expected/got blobs."""
    monkeypatch.setattr(conftest, "UPDATE_EXPECTED", False)

    expected_file = tmp_path / "output.txt"
    expected_file.write_text("line1\nline2\n")
    actual = "line1\nCHANGED\n"

    with pytest.raises(pytest.fail.Exception) as exc:
        conftest.check_or_update(actual, expected_file, "Output")

    msg = str(exc.value)
    assert "Output differs:" in msg
    assert f"--- {expected_file}" in msg
    assert "+++ actual" in msg
    assert "-line2" in msg
    assert "+CHANGED" in msg
    # Without name_function the divergence site is not reported.
    assert "diverges " not in msg


GEN_CPP = """\
// Generated by TurboPython Compiler
#include "main.hpp"

namespace tpyapp::main {

// def first(items: list[int32]) -> int32:
int32_t first(const std::vector<int32_t>& items) {
    // return items[0]
    return ::tpy::__getitem__(items, 0);
}

// def second(items: list[int32]) -> int32:
int32_t second(const std::vector<int32_t>& items) {
    // return items[1]
    return ::tpy::__getitem__(items, 1);
}

} // namespace tpyapp::main
"""

GEN_HPP = """\
// Generated by TurboPython Compiler
#pragma once

namespace tpyapp::main {

// class Counter:
struct Counter {
    // value: int32
    int32_t value;

    // def __init__(self, start: int32):
    Counter() = default;
    explicit Counter(int32_t start) : value(start) {}

    // def get(self) -> int32:
    int32_t get() const;
};

// def get(self) -> int32:
inline int32_t Counter::get() const {
    // return self.value
    return this->value;
}

} // namespace tpyapp::main
"""


class TestFirstDivergentLine:
    def test_equal_returns_none(self) -> None:
        assert conftest.first_divergent_line("a\nb\n", "a\nb\n") is None

    def test_changed_line(self) -> None:
        assert conftest.first_divergent_line("a\nb\nc\n", "a\nX\nc\n") == 1

    def test_deleted_line_anchors_at_gap(self) -> None:
        assert conftest.first_divergent_line("a\nb\nc\n", "a\nc\n") == 1


class TestEnclosingFunction:
    def test_free_function(self) -> None:
        lines = GEN_CPP.splitlines()
        idx = lines.index("    return ::tpy::__getitem__(items, 1);")
        assert conftest.enclosing_function(lines, idx) == "second"

    def test_method_out_of_line(self) -> None:
        lines = GEN_HPP.splitlines()
        idx = lines.index("    return this->value;")
        assert conftest.enclosing_function(lines, idx) == "get"

    def test_ctor_qualifies_with_record(self) -> None:
        lines = GEN_HPP.splitlines()
        idx = lines.index("    explicit Counter(int32_t start) : value(start) {}")
        assert conftest.enclosing_function(lines, idx) == "Counter.__init__"

    def test_struct_field_hits_class_marker(self) -> None:
        lines = GEN_HPP.splitlines()
        idx = lines.index("    int32_t value;")
        assert conftest.enclosing_function(lines, idx) == "class Counter"

    def test_preamble_has_no_marker(self) -> None:
        assert conftest.enclosing_function(GEN_CPP.splitlines(), 1) is None


class TestDivergenceSiteReport:
    def _fail_msg(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch,
                  actual: str) -> str:
        monkeypatch.setattr(conftest, "UPDATE_EXPECTED", False)
        expected_file = tmp_path / "main.cpp"
        expected_file.write_text(GEN_CPP)
        with pytest.raises(pytest.fail.Exception) as exc:
            conftest.check_or_update(actual, expected_file, "main.cpp",
                                     name_function=True)
        return str(exc.value)

    def test_names_the_enclosing_function(
            self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        actual = GEN_CPP.replace("__getitem__(items, 1)", "items[1]")
        msg = self._fail_msg(tmp_path, monkeypatch, actual)
        assert "diverges in `second`" in msg

    def test_divergence_before_any_marker(self, tmp_path: Path,
                                          monkeypatch: pytest.MonkeyPatch) -> None:
        actual = GEN_CPP.replace('#include "main.hpp"', '#include "other.hpp"')
        msg = self._fail_msg(tmp_path, monkeypatch, actual)
        assert "outside any function marker" in msg

    def test_dropped_lines_fall_back_to_expected_side(
            self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        # Dropping a whole function body can leave actual's divergence point on
        # a marker-free line; the expected side still names it.
        actual = GEN_CPP.replace(
            "    // return items[1]\n"
            "    return ::tpy::__getitem__(items, 1);\n", "")
        msg = self._fail_msg(tmp_path, monkeypatch, actual)
        assert "in `second`" in msg


BAD_PASCAL = """\
program ErrorSyntax;
begin
  writeln('unterminated call';
end.
"""


def test_frontend_plugin_parse_error_fails_the_compile(tmp_path: Path) -> None:
    """A plugin PARSE error must fail the case, not read as a clean compile.

    The plugin's error is an ERROR on `compiler.diagnostics`: `Compiler.compile()`
    records it and RETURNS rather than raising, so a `has_errors` that counts only
    module-analyzer diagnostics reports success and the harness walks on into
    codegen. There is no `error_` case that can pin this -- the annotation gate
    reads `src/*.py` only, so a case whose sources are all plugin-extension files
    cannot carry the `# tpyc: error(...)` leg it demands.
    """
    case_dir = tmp_path / "error_plugin_syntax"
    src_dir = case_dir / "src"
    src_dir.mkdir(parents=True)
    (case_dir / "options.json").write_text(
        '{"plugin": "frontends/pascal/pascal_frontend.py",'
        ' "dsl_opts": {"sdl": "off"}}\n')
    src_file = src_dir / "main.pas"
    src_file.write_text(BAD_PASCAL)

    result = conftest.compile_with_diagnostics(src_file, case_dir / "out")

    assert result.success is False
    assert "main.pas:3: error: expected RPAREN, got SEMI ';'" in result.diagnostics
