#!/usr/bin/env python3
"""Vendor zlib source into runtime/cpp/third_party/zlib/.

Idempotent: if the target tree already matches the pinned version (per the
sidecar marker), this script is a no-op.

Usage:
    uv run python scripts/vendor_zlib.py          # download + extract + strip
    uv run python scripts/vendor_zlib.py --force   # re-vendor even if marker matches

To bump zlib:
    1. Update VERSION + SHA256 below (the release tarball on GitHub).
    2. Run this script (without --force).
    3. Review the diff under runtime/cpp/third_party/zlib/; if upstream
       added or renamed library sources, update SOURCES below.
    4. Commit.
"""

from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import shutil
import sys
import tarfile
import tempfile
import urllib.request
from pathlib import Path

# ---- Pinned zlib release ----
NAME = "zlib"
VERSION = "1.3.2"
URL = (
    "https://github.com/madler/zlib/releases/download/"
    f"v{VERSION}/zlib-{VERSION}.tar.gz"
)
SHA256 = "bb329a0a2cd0274d05519d61c667c062e06990d72e125ee2dfa8de64f0119d16"

# ---- Vendoring layout ----
# Sidecar metadata + the source manifest live NEXT TO the vendored tree, not
# inside it -- the upstream source tree stays pristine.
REPO_ROOT = Path(__file__).resolve().parent.parent
THIRD_PARTY_DIR = REPO_ROOT / "runtime" / "cpp" / "third_party"
DEST_DIR = THIRD_PARTY_DIR / NAME
SIDECAR = THIRD_PARTY_DIR / f"{NAME}.vendor.json"
MANIFEST = THIRD_PARTY_DIR / f"{NAME}.sources.txt"

# The core library, minus the gzFile API (gz*.c): the gzip module is written
# in TPy over the stream API, and gz*.c would drag in unistd/stdarg config.
SOURCES: tuple[str, ...] = (
    "adler32.c", "compress.c", "crc32.c", "deflate.c", "infback.c",
    "inffast.c", "inflate.c", "inftrees.c", "trees.c", "uncompr.c",
    "zutil.c",
)
HEADERS: tuple[str, ...] = (
    "zlib.h", "zconf.h", "zutil.h", "crc32.h", "deflate.h", "trees.h",
    "inflate.h", "inffast.h", "inftrees.h", "inffixed.h",
    # zutil.c includes gzguts.h for its gz-free error-string helper.
    "gzguts.h",
)
# Keep-list, not strip-list: the tarball also carries contrib/, tests, docs,
# per-platform build files and an upstream CMakeLists.txt that renames
# zconf.h inside the source tree on an out-of-tree build.
KEEP: tuple[str, ...] = SOURCES + HEADERS + ("LICENSE", "README")


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def _download(url: str, dest: Path) -> None:
    print(f"  downloading {url}", file=sys.stderr)
    with urllib.request.urlopen(url, timeout=120) as resp:
        with open(dest, "wb") as f:
            shutil.copyfileobj(resp, f)


def _extract(tarball: Path, dest: Path) -> None:
    """Extract the kept files, stripping the top-level zlib-VERSION/ prefix."""
    print(f"  extracting -> {dest}", file=sys.stderr)
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    prefix = f"zlib-{VERSION}/"
    with tarfile.open(tarball, "r:gz") as tar:
        members = []
        for m in tar.getmembers():
            if not m.name.startswith(prefix):
                continue
            stripped = m.name[len(prefix):]
            if stripped not in KEEP:
                continue
            m.name = stripped
            members.append(m)
        missing = set(KEEP) - {m.name for m in members}
        if missing:
            raise SystemExit(f"ERROR: tarball lacks {sorted(missing)}")
        try:
            tar.extractall(dest, members=members, filter="data")
        except TypeError:
            tar.extractall(dest, members=members)


def _write_cmakelists(dest: Path) -> None:
    """A minimal static-library CMakeLists.txt for the bundled CMake-emit
    path (`tpyc -o`), matching the direct-compile source list. Regenerated
    on every vendor run, so it is a TPy build artifact, not upstream."""
    srcs = "\n".join(f'    "${{CMAKE_CURRENT_LIST_DIR}}/{s}"' for s in SOURCES)
    text = (
        "# Generated by scripts/vendor_zlib.py -- TPy build shim.\n"
        "# Builds one static lib from the vendored zlib sources, matching\n"
        "# the direct-compile path. Not upstream's CMake.\n"
        "cmake_minimum_required(VERSION 3.16)\n"
        "project(zlib_bundled C)\n"
        "add_library(zlibstatic STATIC\n"
        f"{srcs})\n"
        "target_include_directories(zlibstatic\n"
        '    PUBLIC "${CMAKE_CURRENT_LIST_DIR}")\n'
    )
    (dest / "CMakeLists.txt").write_text(text)


def _write_manifest() -> None:
    header = (
        "# Generated by scripts/vendor_zlib.py -- do not edit by hand.\n"
        "# One zlib library source per line, relative to the vendored dir.\n"
        "# The gzFile API (gz*.c) is deliberately not built: the gzip module\n"
        "# is pure TPy over the z_stream API.\n"
    )
    MANIFEST.write_text(header + "\n".join(SOURCES) + "\n")


def _read_sidecar() -> dict | None:
    if not SIDECAR.is_file():
        return None
    try:
        return json.loads(SIDECAR.read_text())
    except (json.JSONDecodeError, OSError):
        return None


def _stamp(metadata: dict) -> str:
    """Reuse the prior `vendored_at` when every substantive field is
    unchanged, so a --force re-run producing identical content is a no-op."""
    prior = _read_sidecar()
    if prior is not None and "vendored_at" in prior \
            and all(prior.get(k) == v for k, v in metadata.items()):
        return prior["vendored_at"]
    return datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")


def _write_sidecar() -> None:
    metadata = {"name": NAME, "version": VERSION, "url": URL, "sha256": SHA256}
    metadata["vendored_at"] = _stamp(metadata)
    SIDECAR.write_text(json.dumps(metadata, indent=2) + "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument(
        "--force", action="store_true",
        help="re-vendor even if the version marker already matches",
    )
    args = parser.parse_args()

    prior = _read_sidecar()
    current = prior.get("version") if prior is not None else None
    if not args.force and current == VERSION:
        print(f"zlib {VERSION} already vendored "
              f"(per {SIDECAR.relative_to(REPO_ROOT)})", file=sys.stderr)
        print("Pass --force to re-vendor.", file=sys.stderr)
        return 0

    print(f"Vendoring zlib {VERSION}", file=sys.stderr)
    with tempfile.TemporaryDirectory(prefix="vendor_zlib_") as tmp:
        tarball = Path(tmp) / f"zlib-{VERSION}.tar.gz"
        _download(URL, tarball)
        actual = _sha256(tarball)
        if actual != SHA256:
            print("ERROR: SHA256 mismatch", file=sys.stderr)
            print(f"  expected: {SHA256}", file=sys.stderr)
            print(f"  actual:   {actual}", file=sys.stderr)
            return 1
        print(f"  sha256 verified: {actual}", file=sys.stderr)
        _extract(tarball, DEST_DIR)

    _write_cmakelists(DEST_DIR)
    _write_manifest()
    _write_sidecar()

    files = [p for p in DEST_DIR.rglob("*") if p.is_file()]
    size_kb = sum(p.stat().st_size for p in files) / 1024
    print(f"Done. {len(files)} files, {size_kb:.0f} KiB at {DEST_DIR}",
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
