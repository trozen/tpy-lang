#!/usr/bin/env python3
"""Vendor mbedTLS source into runtime/cpp/third_party/mbedtls/.

Idempotent: if the target tree already matches the pinned version (per the
sidecar marker), this script is a no-op.

Usage:
    uv run python scripts/vendor_mbedtls.py          # download + extract + strip
    uv run python scripts/vendor_mbedtls.py --force   # re-vendor even if marker matches

To bump mbedTLS:
    1. Update VERSION + SHA256 + URL below (SHA256 is published as the
       mbedtls-<v>-sha256sum.txt release asset).
    2. Run this script (without --force).
    3. Review the diff under runtime/cpp/third_party/mbedtls/ and regenerate
       the facade header if the upstream API surface we use changed.
    4. Commit.

We pin the 3.6.x LTS line: it carries the documented mbedtls_ssl_* client
API the ssl module binds, and is maintained for years. The 4.x line
reorganized crypto (PSA-only) and is deferred to a future bump.
"""

from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import shutil
import sys
import tarfile
import tempfile
import urllib.request
from pathlib import Path

# ---- Pinned mbedTLS release ----
NAME = "mbedtls"
VERSION = "3.6.6"
URL = (
    "https://github.com/Mbed-TLS/mbedtls/releases/download/"
    f"mbedtls-{VERSION}/mbedtls-{VERSION}.tar.bz2"
)
SHA256 = "8fb65fae8dcae5840f793c0a334860a411f884cc537ea290ce1c52bb64ca007a"

# ---- Vendoring layout ----
# Sidecar metadata + the generated source manifest live NEXT TO the vendored
# tree, not inside it -- the upstream source tree stays pristine.
REPO_ROOT = Path(__file__).resolve().parent.parent
THIRD_PARTY_DIR = REPO_ROOT / "runtime" / "cpp" / "third_party"
DEST_DIR = THIRD_PARTY_DIR / NAME
SIDECAR = THIRD_PARTY_DIR / f"{NAME}.vendor.json"
MANIFEST = THIRD_PARTY_DIR / f"{NAME}.sources.txt"

# Keep-list, not strip-list: the release asset carries ~45 MiB of tests,
# programs, docs, framework, build scaffolding, and optional 3rdparty crypto
# (everest / p256-m, both OFF in the default config). We only need the C
# library sources, the public+private headers, and the license. Compiling
# the library needs exactly `-I include -I library` (config is picked up
# automatically via mbedtls/build_info.h).
KEEP_TOP: tuple[str, ...] = ("library", "include", "LICENSE")

# Non-source scaffolding to prune from inside the kept dirs.
PRUNE_NAMES: tuple[str, ...] = ("CMakeLists.txt", "Makefile", ".gitignore")


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def _download(url: str, dest: Path) -> None:
    print(f"  downloading {url}", file=sys.stderr)
    with urllib.request.urlopen(url, timeout=120) as resp:
        with open(dest, "wb") as f:
            shutil.copyfileobj(resp, f)


def _extract(tarball: Path, dest: Path) -> None:
    """Extract tarball into dest, stripping the top-level mbedtls-VERSION/ prefix."""
    print(f"  extracting -> {dest}", file=sys.stderr)
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    with tarfile.open(tarball, "r:bz2") as tar:
        prefix = f"mbedtls-{VERSION}/"
        members = []
        for m in tar.getmembers():
            if not m.name.startswith(prefix):
                continue
            stripped = m.name[len(prefix):]
            if not stripped:
                continue  # the top-level dir entry itself
            # Only extract what we keep -- avoids unpacking 45 MiB to prune it.
            top = stripped.split("/", 1)[0]
            if top not in KEEP_TOP:
                continue
            m.name = stripped
            members.append(m)
        try:
            tar.extractall(dest, members=members, filter="data")
        except TypeError:
            tar.extractall(dest, members=members)


def _prune(dest: Path) -> None:
    print("  pruning build scaffolding", file=sys.stderr)
    for name in PRUNE_NAMES:
        for path in dest.rglob(name):
            if path.is_file():
                path.unlink()


def _write_cmakelists(dest: Path) -> None:
    """Write a minimal static-library CMakeLists.txt for the bundled
    CMake-emit path (`tpyc -o`). Upstream's CMake is stripped (it pulls in
    the test framework + a 3-target split we don't need); this shim builds
    one `mbedtls` static lib from library/*.c, matching the direct-compile
    path. Regenerated on every vendor run, so it is a TPy build artifact,
    not pristine upstream source."""
    text = (
        "# Generated by scripts/vendor_mbedtls.py -- TPy build shim.\n"
        "# Builds a single static lib from the vendored mbedTLS sources,\n"
        "# matching the direct-compile path. Not upstream's CMake.\n"
        "cmake_minimum_required(VERSION 3.16)\n"
        "project(mbedtls_bundled C)\n"
        'file(GLOB MBEDTLS_SOURCES "${CMAKE_CURRENT_LIST_DIR}/library/*.c")\n'
        "add_library(mbedtls STATIC ${MBEDTLS_SOURCES})\n"
        "target_include_directories(mbedtls\n"
        '    PUBLIC  "${CMAKE_CURRENT_LIST_DIR}/include"\n'
        '    PRIVATE "${CMAKE_CURRENT_LIST_DIR}/library")\n'
    )
    (dest / "CMakeLists.txt").write_text(text)


def _write_manifest(dest: Path) -> int:
    """Enumerate library/*.c (all compile standalone; none is #included by
    another) into the source manifest, paths relative to library/."""
    lib = dest / "library"
    sources = sorted(p.name for p in lib.glob("*.c"))
    header = (
        "# Generated by scripts/vendor_mbedtls.py -- do not edit by hand.\n"
        "# One mbedTLS library source per line, relative to library/.\n"
    )
    MANIFEST.write_text(header + "\n".join(sources) + "\n")
    return len(sources)


def _write_sidecar() -> None:
    metadata = {
        "name": NAME,
        "version": VERSION,
        "url": URL,
        "sha256": SHA256,
        "vendored_at": datetime.datetime.now(datetime.timezone.utc)
            .isoformat(timespec="seconds"),
    }
    SIDECAR.write_text(json.dumps(metadata, indent=2) + "\n")


def _read_sidecar_version() -> str | None:
    if not SIDECAR.is_file():
        return None
    try:
        return json.loads(SIDECAR.read_text()).get("version")
    except (json.JSONDecodeError, OSError):
        return None


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument(
        "--force", action="store_true",
        help="re-vendor even if the version marker already matches",
    )
    args = parser.parse_args()

    current = _read_sidecar_version()
    if not args.force and current == VERSION:
        print(f"mbedTLS {VERSION} already vendored "
              f"(per {SIDECAR.relative_to(REPO_ROOT)})", file=sys.stderr)
        print("Pass --force to re-vendor.", file=sys.stderr)
        return 0
    if current and current != VERSION:
        print(f"Sidecar says mbedTLS {current}, want {VERSION} -- re-vendoring",
              file=sys.stderr)

    print(f"Vendoring mbedTLS {VERSION}", file=sys.stderr)
    with tempfile.TemporaryDirectory(prefix="vendor_mbedtls_") as tmp:
        tarball = Path(tmp) / f"mbedtls-{VERSION}.tar.bz2"
        _download(URL, tarball)
        actual = _sha256(tarball)
        if actual != SHA256:
            print("ERROR: SHA256 mismatch", file=sys.stderr)
            print(f"  expected: {SHA256}", file=sys.stderr)
            print(f"  actual:   {actual}", file=sys.stderr)
            return 1
        print(f"  sha256 verified: {actual}", file=sys.stderr)
        _extract(tarball, DEST_DIR)

    _prune(DEST_DIR)
    _write_cmakelists(DEST_DIR)
    n_sources = _write_manifest(DEST_DIR)
    _write_sidecar()

    file_count = sum(1 for _ in DEST_DIR.rglob("*") if _.is_file())
    size_mb = sum(p.stat().st_size for p in DEST_DIR.rglob("*") if p.is_file()) / (1024 * 1024)
    print(f"Done. {file_count} files ({n_sources} sources), "
          f"{size_mb:.1f} MiB at {DEST_DIR}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
