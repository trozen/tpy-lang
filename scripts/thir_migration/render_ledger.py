#!/usr/bin/env python3
"""Render the THIR AST-arm convertibility ledger from a residual dump.

An arm's residual = number of fallback bodies still keeping that AST emit
arm alive. Residual 0 => the arm is fully convertible (no body falls back
through it) => deletable. When every arm reaches 0, fallback is 0 and the
whole AST emit path can be deleted.

Produce the input JSON with the (cheap, ~15-min) metrics pass -- NOT the
2-hour coverage residency:

    THIR_ARM_RESIDUAL_JSON=/tmp/arm_residual.json \\
        uv run pytest --thir-codegen --no-exec -q

Then:

    python scripts/thir_migration/render_ledger.py /tmp/arm_residual.json \\
        > docs/THIR_ARM_LEDGER.md
"""
import json
import sys


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit("usage: render_ledger.py <arm_residual.json>")
    data = json.load(open(sys.argv[1]))
    items = sorted(((k, v) for k, v in data.items() if isinstance(v, (int, float))),
                   key=lambda kv: kv[1])
    deletable = [k for k, v in items if v == 0]
    out = [
        "# THIR AST-arm convertibility ledger",
        "",
        "Auto-generated by `scripts/thir_migration/render_ledger.py` from a",
        "`$THIR_ARM_RESIDUAL_JSON` metrics dump. Do not hand-edit -- refresh by",
        "re-running the metrics pass + this script.",
        "",
        "An arm's **residual** = number of fallback bodies still keeping that AST",
        "emit arm alive. **Residual 0 = fully convertible (deletable)** -- no body",
        "falls back through it. When every arm reaches 0, fallback is 0 and the AST",
        "emit path can be deleted. The ubiquitous arms (`name`, `call`, `var_decl`,",
        "...) sit in nearly every fallback body, so they only reach 0 at the very",
        "end -- 'all arms at 0' is equivalent to 'fallback = 0'. The small-residual",
        "arms are the incremental deletion-progress view.",
        "",
        f"**{len(deletable)}/{len(items)} arms deletable (residual 0).**",
        "",
        "| residual | arm | status |",
        "|---:|---|---|",
    ]
    for k, v in items:
        out.append(f"| {int(v)} | `{k}` | {'**DELETABLE**' if v == 0 else ''} |")
    print("\n".join(out))


if __name__ == "__main__":
    main()
