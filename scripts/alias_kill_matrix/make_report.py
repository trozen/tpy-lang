"""Builds RESULTS.md from every results_<label>.json next to this file.

Run: uv run python scripts/alias_kill_matrix/run_matrix.py --report
"""
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
GROUP_ORDER = {"inline": 0, "pointer": 1, "unmodelled": 2, "meet": 3, "everyday": 4,
               "view": 5, "cost": 9}
NOT_A_VERDICT = ("REJECT", "CRASH", "TIMEOUT", "UNKNOWN", "NO-DECL", "AMBIGUOUS")


def load() -> dict[str, dict]:
    out = {}
    for p in sorted(HERE.glob("results_*.json")):
        d = json.loads(p.read_text())
        out[d["label"]] = d
    # the committed baseline first, then the rest in file order
    labels = sorted(out, key=lambda l: (l != "master", l))
    return {l: out[l] for l in labels}


_GENERATED: dict[str, str] = {}


def current_sha(name: str) -> str | None:
    """The hash of the row as the generator writes it today."""
    if not _GENERATED:
        sys.path.insert(0, str(HERE))
        import gen_shapes
        for p in gen_shapes.generate(HERE / "build" / "shapes"):
            _GENERATED[p.stem] = hashlib.sha256(p.read_bytes()).hexdigest()[:12]
    return _GENERATED.get(name)


def esc(s: str) -> str:
    return s.replace("|", "\\|")


def main() -> None:
    res = load()
    labels = list(res)
    rows_of = lambda l: res[l]["rows"]
    names = sorted({n for d in res.values() for n in d["rows"]},
                   key=lambda n: (GROUP_ORDER.get(next(d["rows"][n]["group"] for d in res.values() if n in d["rows"]), 8), n))
    first = lambda n: next(res[l]["rows"][n] for l in labels if n in res[l]["rows"])
    verdict = lambda l, n: rows_of(l).get(n, {}).get("verdict", "-")
    expected = lambda n: first(n).get("accepted") or first(n)["expected"]
    nc = [n for n in names if first(n)["group"] != "cost"]

    L = ["# Narrowing-kill acceptance matrix", "",
         "Generated by `run_matrix.py --report`; do not edit. See README.md for "
         "the verdict and truth rules.", "",
         "Trees: " + ", ".join(f"`{l}` = {res[l]['repo']} @ {res[l].get('commit', '?')}" for l in labels) + ".", ""]

    # Cost rows are deterministic output of gen_cost.py; nothing to compare.
    stale = [(l, n) for l in labels for n in rows_of(l)
             if rows_of(l)[n]["group"] != "cost" and rows_of(l)[n].get("sha")
             and rows_of(l)[n]["sha"] != current_sha(n)]
    if stale:
        L += ["**Stale rows** (the shape changed after the run; re-measure): "
              + ", ".join(f"`{l}`:{n}" for l, n in stale), ""]

    L += ["| shape | group | truth | expected | accepted | " + " | ".join(labels) + " | note |",
          "|" + "---|" * (6 + len(labels))]
    for n in nc:
        r0 = first(n)
        notes = list(r0.get("notes", []))
        if r0.get("why"):
            notes.insert(0, r0["why"])
        for l in labels:
            r = rows_of(l).get(n)
            if r and r.get("verdict") in NOT_A_VERDICT and r.get("detail"):
                notes.append(f"{l}: {r['detail']}")
        cols = [verdict(l, n) for l in labels]
        L.append(f"| {n} | {r0['group']} | {r0.get('truth', '-')} | {r0['expected']} | "
                 f"{r0.get('accepted') or ''} | " + " | ".join(cols) + f" | {esc('; '.join(notes))} |")
    L.append("")

    L += ["## Summary", ""]
    for l in labels:
        cnt: dict[str, int] = {}
        for n in nc:
            cnt[verdict(l, n)] = cnt.get(verdict(l, n), 0) + 1
        silent = [n for n in nc if first(n).get("truth") == "None-reaches" and verdict(l, n) == "UNCHECKED"]
        over = [n for n in nc if first(n).get("truth") == "stays-value" and verdict(l, n) == "CHECKED"]
        L.append(f"- `{l}`: " + ", ".join(f"{k} {v}" for k, v in sorted(cnt.items())) +
                 f"; silently wrong (None-reaches + UNCHECKED) {len(silent)}; "
                 f"checked although truth stays-value {len(over)}")
    L.append("")

    for l in labels:
        off = [n for n in nc if verdict(l, n) not in NOT_A_VERDICT
               and verdict(l, n) != expected(n).split(" ")[0]]
        L += [f"### `{l}` differs from expected/accepted ({len(off)})", ""]
        L += [f"- {n}: expected {expected(n)}, got {verdict(l, n)}, truth {first(n).get('truth')}" for n in off] or ["none"]
        L.append("")

    base = labels[0]
    for l in labels[1:]:
        changed = [n for n in nc if n in rows_of(l) and n in rows_of(base) and verdict(l, n) != verdict(base, n)]
        L += [f"### `{l}` vs `{base}` ({len(changed)} rows changed)", "",
              f"| shape | truth | expected | {base} | {l} |", "|---|---|---|---|---|"]
        L += [f"| {n} | {first(n).get('truth')} | {expected(n)} | {verdict(base, n)} | {verdict(l, n)} |" for n in changed]
        L.append("")
        # A row whose accepted verdict is REJECT documents a rejection the
        # shipped rule makes on purpose; it is no regression.
        newly = [n for n in changed if verdict(base, n) not in NOT_A_VERDICT and verdict(l, n) in NOT_A_VERDICT
                 and expected(n).split(" ")[0] != "REJECT"]
        L += [f"### `{l}` no longer compiles ({len(newly)}) -- the must-still-compile gate", ""]
        L += [f"- {n}: {rows_of(l)[n].get('detail', '')}" for n in newly] or ["none"]
        L.append("")

    rej = [n for n in nc if all(verdict(l, n) in NOT_A_VERDICT for l in labels)]
    L += [f"### Not a verdict on every tree ({len(rej)})", "", ", ".join(rej) or "none", ""]

    L += ["## Cost", "",
          "seconds = wall time of `tpyc file.py -o out --no-bundle-runtime` (sequential, 60 s "
          "timeout); delta/ratio against the tree's trivial-program baseline (min of 3). "
          "Expected: within 2x of baseline.", "",
          "| shape | " + " | ".join(f"{l} s (delta, ratio)" for l in labels) + " | expected | note |",
          "|" + "---|" * (3 + len(labels))]
    for n in names:
        r0 = first(n)
        if r0["group"] != "cost":
            continue
        cols = []
        for l in labels:
            r = rows_of(l).get(n)
            if not r:
                cols.append("-")
            elif r.get("seconds") is None:
                cols.append("TIMEOUT")
            else:
                cols.append(f"{r['seconds']} (+{r['seconds'] - r['baseline']:.2f}, {r['ratio']}x)" +
                            (f" {r['detail'][:60]}" if r.get("detail") else ""))
        L.append(f"| {n} | " + " | ".join(cols) + f" | {r0['expected']} | {esc('; '.join(r0.get('notes', [])))} |")
    L.append("")
    L += ["Baselines: " + ", ".join(f"`{l}` {res[l].get('baseline_seconds')} s" for l in labels), ""]
    (HERE / "RESULTS.md").write_text("\n".join(L) + "\n")
    print("wrote", HERE / "RESULTS.md")


if __name__ == "__main__":
    main()
