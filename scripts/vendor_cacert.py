#!/usr/bin/env python3
"""Vendor the Mozilla CA root bundle into runtime/cpp/third_party/cacert/.

Idempotent: if the target already matches the pinned version (per the
sidecar marker), this script is a no-op.

Usage:
    uv run python scripts/vendor_cacert.py           # download + verify + generate
    uv run python scripts/vendor_cacert.py --force    # re-vendor even if marker matches

To bump the bundle:
    1. Update VERSION + SHA256 below (pick a certifi release tag; SHA256 is
       `sha256sum` of that tag's certifi/cacert.pem).
    2. Run this script (without --force).
    3. Review the diff under runtime/cpp/third_party/cacert/ and commit.

We track `certifi` (not curl.se) as the source: it is the same Mozilla NSS
root set, it is what CPython's `requests` trusts by default, and it is
reachable over IPv4 GitHub (curl.se is IPv6-only from some networks). The
bundle is embedded as a compiled-in C string literal (cacert_data.c) rather than a
runtime file path -- the ssl module parses the buffer directly, so the
default trust store is hermetic (no install-layout / cwd dependence).
"""

from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import sys
import tempfile
import urllib.request
from pathlib import Path

# ---- Pinned certifi release ----
NAME = "cacert"
VERSION = "2026.06.17"
URL = (
    "https://raw.githubusercontent.com/certifi/python-certifi/"
    f"{VERSION}/certifi/cacert.pem"
)
SHA256 = "bbc7e9c01d7551bb8a159b5dedd989b8ee3ce105aff522b68eb1b01bf854cab0"

# ---- Vendoring layout ----
REPO_ROOT = Path(__file__).resolve().parent.parent
THIRD_PARTY_DIR = REPO_ROOT / "runtime" / "cpp" / "third_party"
DEST_DIR = THIRD_PARTY_DIR / NAME
PEM_FILE = DEST_DIR / "cacert.pem"
BLOB_FILE = DEST_DIR / "cacert_data.c"
SIDECAR = THIRD_PARTY_DIR / f"{NAME}.vendor.json"


def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _download(url: str) -> bytes:
    print(f"  downloading {url}", file=sys.stderr)
    with urllib.request.urlopen(url, timeout=120) as resp:
        return resp.read()


def _cert_count(pem: bytes) -> int:
    return pem.count(b"-----BEGIN CERTIFICATE-----")


def _c_escape(line: bytes) -> str:
    """Escape one PEM line for a C string literal. certifi's `# Label: "..."`
    comment lines carry double quotes; everything else is base64 / printable
    ASCII. Non-printables get octal escapes so the emitted byte is exact."""
    out: list[str] = []
    for b in line:
        if b == 0x22:      # "
            out.append('\\"')
        elif b == 0x5c:    # backslash
            out.append("\\\\")
        elif 0x20 <= b < 0x7f:
            out.append(chr(b))
        else:
            out.append(f"\\{b:03o}")
    return "".join(out)


def _write_blob(pem: bytes) -> None:
    """Emit cacert_data.c: the PEM text as a C string literal, one adjacent
    literal per source line (concatenation sidesteps any single-literal length
    limit). An `unsigned char[]` may be initialized from a string literal (C11
    6.7.9p14), which appends the terminating NUL mbedtls_x509_crt_parse needs;
    sizeof then yields the exact length (PEM bytes + NUL)."""
    parts = pem.split(b"\n")
    body_lines = [f'  "{_c_escape(line)}\\n"' for line in parts[:-1]]
    if parts[-1]:  # a final line with no trailing newline (PEM normally ends in \n)
        body_lines.append(f'  "{_c_escape(parts[-1])}"')
    body = "\n".join(body_lines)
    text = (
        "/* Generated by scripts/vendor_cacert.py -- do not edit by hand.\n"
        f"   Mozilla CA root bundle via certifi {VERSION}, embedded as a C\n"
        "   string literal so the ssl module's default trust store is compiled\n"
        "   in (no runtime file path). The string literal's implicit trailing\n"
        "   NUL is what mbedtls_x509_crt_parse treats as the PEM terminator, so\n"
        "   sizeof(...) is the length to pass (text bytes + NUL). */\n"
        "#include <stddef.h>\n\n"
        "const unsigned char tpy_cacert_pem[] =\n"
        f"{body};\n\n"
        "const size_t tpy_cacert_pem_len = sizeof(tpy_cacert_pem);\n"
    )
    BLOB_FILE.write_text(text)


def _stamp(metadata: dict) -> str:
    """Timestamp for `vendored_at`: reuse the prior one when every substantive
    field is unchanged, so a re-run producing identical content (e.g. --force,
    or an emit-format tweak) is a true no-op instead of churning the timestamp."""
    prior = _read_sidecar()
    if prior is not None and "vendored_at" in prior \
            and all(prior.get(k) == v for k, v in metadata.items()):
        return prior["vendored_at"]
    return datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")


def _write_sidecar(pem: bytes) -> None:
    metadata = {
        "name": NAME,
        "version": VERSION,
        "url": URL,
        "sha256": SHA256,
        "cert_count": _cert_count(pem),
    }
    metadata["vendored_at"] = _stamp(metadata)
    SIDECAR.write_text(json.dumps(metadata, indent=2) + "\n")


def _read_sidecar() -> dict | None:
    if not SIDECAR.is_file():
        return None
    try:
        return json.loads(SIDECAR.read_text())
    except (json.JSONDecodeError, OSError):
        return None


def _read_sidecar_version() -> str | None:
    prior = _read_sidecar()
    return prior.get("version") if prior is not None else None


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument(
        "--force", action="store_true",
        help="re-vendor even if the version marker already matches",
    )
    args = parser.parse_args()

    current = _read_sidecar_version()
    if not args.force and current == VERSION:
        print(f"CA bundle {VERSION} already vendored "
              f"(per {SIDECAR.relative_to(REPO_ROOT)})", file=sys.stderr)
        print("Pass --force to re-vendor.", file=sys.stderr)
        return 0
    if current and current != VERSION:
        print(f"Sidecar says {current}, want {VERSION} -- re-vendoring",
              file=sys.stderr)

    print(f"Vendoring Mozilla CA bundle (certifi {VERSION})", file=sys.stderr)
    with tempfile.TemporaryDirectory(prefix="vendor_cacert_"):
        pem = _download(URL)
    actual = _sha256_bytes(pem)
    if actual != SHA256:
        print("ERROR: SHA256 mismatch", file=sys.stderr)
        print(f"  expected: {SHA256}", file=sys.stderr)
        print(f"  actual:   {actual}", file=sys.stderr)
        return 1
    print(f"  sha256 verified: {actual}", file=sys.stderr)

    DEST_DIR.mkdir(parents=True, exist_ok=True)
    PEM_FILE.write_bytes(pem)
    _write_blob(pem)
    _write_sidecar(pem)

    n = _cert_count(pem)
    kb = (len(pem) + 1) / 1024
    print(f"Done. {n} roots, {kb:.1f} KiB blob at {BLOB_FILE}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
