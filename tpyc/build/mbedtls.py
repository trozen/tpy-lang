"""mbedTLS-specific build wiring. Registered in
``tpyc/build/third_party.py::_FACTORIES``.

The vendored mbedTLS tree is the C library only (library/ + include/),
with a generated static-lib CMakeLists.txt shim (see
``scripts/vendor_mbedtls.py``). The default ``mbedtls_config.h`` is used
as-is -- it already enables TLS 1.2/1.3, x509, FS_IO, entropy, and both
the client and server sides; the config is picked up automatically via
``mbedtls/build_info.h``, so no ``-D`` is needed (unlike PCRE2). All the
direct-compile path does here is:

  * enumerate library/*.c (from the sidecar manifest
    ``runtime/cpp/third_party/mbedtls.sources.txt``);
  * emit the two -I flags the sources need;
  * point dependents at include/ (which holds ``mbedtls/*.h`` / ``psa/*.h``).
"""

from __future__ import annotations

from pathlib import Path

from .third_party import ThirdPartyLib, read_source_manifest


_SOURCE_MANIFEST = "mbedtls.sources.txt"


def _source_files(lib: ThirdPartyLib) -> list[Path]:
    """The mbedTLS .c files to compile into the static library.

    Reads the sidecar manifest (generated by the vendoring script from
    library/*.c -- every source compiles standalone, none is #included by
    another) rather than globbing, so the build's source set is pinned and
    reviewable alongside a version bump.
    """
    if lib.bundled_source_dir is None:
        raise RuntimeError(f"{lib.name}: no bundled source dir configured")
    lib_dir = lib.bundled_source_dir / "library"
    if not lib_dir.is_dir():
        raise FileNotFoundError(
            f"{lib.name}: bundled library/ not found at {lib_dir}"
        )
    manifest = lib.bundled_source_dir.parent / _SOURCE_MANIFEST
    if not manifest.is_file():
        raise FileNotFoundError(
            f"{lib.name}: source manifest not found at {manifest}"
        )
    paths: list[Path] = []
    for name in read_source_manifest(manifest):
        p = lib_dir / name
        if not p.is_file():
            raise FileNotFoundError(
                f"{lib.name}: expected source file missing: {p} "
                f"(listed in {manifest})"
            )
        paths.append(p)
    return paths


def _compile_flags(lib: ThirdPartyLib) -> list[str]:
    """C-compiler flags to build an mbedTLS .c file. -Iinclude resolves the
    public headers + the default mbedtls_config.h (via build_info.h);
    -Ilibrary resolves the private headers (ssl_misc.h, common.h, ...)."""
    if lib.bundled_source_dir is None:
        raise RuntimeError(f"{lib.name}: no bundled source dir configured")
    return [
        f"-I{lib.bundled_source_dir / 'include'}",
        f"-I{lib.bundled_source_dir / 'library'}",
    ]


def _user_include_dir(lib: ThirdPartyLib) -> Path:
    """Directory holding the public headers (``mbedtls/``, ``psa/``) that the
    facade header and any dependent TU resolve their includes against."""
    if lib.bundled_source_dir is None:
        raise RuntimeError(f"{lib.name}: no bundled source dir configured")
    return lib.bundled_source_dir / "include"


def factory(runtime_cpp_dir: Path) -> ThirdPartyLib:
    """Build the mbedTLS ``ThirdPartyLib`` declaration.

    System mode links all three mbedTLS archives (tls -> x509 -> crypto, in
    dependency order). In CMake mode the upstream config package exports
    ``MbedTLS::mbedtls``, which transitively pulls x509 + crypto.
    """
    return ThirdPartyLib(
        name="mbedtls",
        cli_flag="--mbedtls",
        cmake_var="TPY_MBEDTLS",
        default_mode="bundled",
        min_version="3.6.0",
        find_package_name="MbedTLS",
        find_package_target="MbedTLS::mbedtls",
        pkgconfig_name="mbedtls",
        system_link_flags=("-lmbedtls", "-lmbedx509", "-lmbedcrypto"),
        bundled_source_dir=runtime_cpp_dir / "third_party" / "mbedtls",
        bundled_static_target="mbedtls",
        license_file="LICENSE",
        bundled_source_files=_source_files,
        bundled_compile_flags=_compile_flags,
        bundled_user_include_dir=_user_include_dir,
    )
