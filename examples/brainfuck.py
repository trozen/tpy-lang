#!/usr/bin/env python3
"""Brainfuck interpreter - idiomatic Python version."""


def run(code: str) -> None:
    """Execute a Brainfuck program."""
    mem = [0] * 256
    ptr = 0
    ip = 0

    while ip < len(code):
        c = code[ip]

        if c == '>':
            ptr = (ptr + 1) % 256
        elif c == '<':
            ptr = (ptr - 1) % 256
        elif c == '+':
            mem[ptr] = (mem[ptr] + 1) % 256
        elif c == '-':
            mem[ptr] = (mem[ptr] - 1) % 256
        elif c == '.':
            print(chr(mem[ptr]), end='')
        elif c == '[':
            if mem[ptr] == 0:
                ip = find_matching(code, ip, 1)
        elif c == ']':
            if mem[ptr] != 0:
                ip = find_matching(code, ip, -1)

        ip += 1

    print()


def find_matching(code: str, start: int, direction: int) -> int:
    """Find matching bracket."""
    depth = 1
    pos = start + direction
    while depth > 0:
        if code[pos] == '[':
            depth += direction
        elif code[pos] == ']':
            depth -= direction
        pos += direction
    return pos - direction


